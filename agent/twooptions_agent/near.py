"""Just enough NEAR to send transactions: keys, borsh transaction encoding, signing and RPC.

Kept to the standard library plus `cryptography` so the agent has one small dependency to
audit and to ship inside a TEE image. The encoding is checked byte for byte against
`@near-js/transactions` (tests/fixtures/near_tx_vectors.json, generated by
`app/scripts/near_tx_vectors.ts`).
"""

from __future__ import annotations

import base64
import hashlib
import json
import time
from dataclasses import dataclass, field
from typing import Any

from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
from cryptography.hazmat.primitives.serialization import Encoding, PublicFormat

from .rpc import RpcError, post

TGAS = 10**12
YOCTO_PER_NEAR = 10**24

_B58 = "123456789ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz"
_B58_INDEX = {c: i for i, c in enumerate(_B58)}


def b58encode(b: bytes) -> str:
    n, out = int.from_bytes(b, "big"), ""
    while n:
        n, r = divmod(n, 58)
        out = _B58[r] + out
    return "1" * (len(b) - len(b.lstrip(b"\0"))) + out


def b58decode(s: str) -> bytes:
    n = 0
    for c in s:
        if c not in _B58_INDEX:
            raise ValueError("invalid base58 character")
        n = n * 58 + _B58_INDEX[c]
    body = n.to_bytes((n.bit_length() + 7) // 8, "big")
    return b"\0" * (len(s) - len(s.lstrip("1"))) + body


# ---------------------------------------------------------------------------------------------
# Keys
# ---------------------------------------------------------------------------------------------


def parse_secret_key(s: str) -> Ed25519PrivateKey:
    """Accepts NEAR's `ed25519:<base58>` (64-byte seed+public or 32-byte seed) or 64 hex chars."""
    s = s.strip()
    if s.startswith("ed25519:"):
        raw = b58decode(s.removeprefix("ed25519:"))
    else:
        try:
            raw = bytes.fromhex(s)
        except ValueError as e:
            raise ValueError("secret key must be ed25519:<base58> or hex") from e
    if len(raw) not in (32, 64):
        raise ValueError(f"secret key must be 32 or 64 bytes, got {len(raw)}")
    key = Ed25519PrivateKey.from_private_bytes(raw[:32])
    if len(raw) == 64 and public_key_bytes(key) != raw[32:]:
        raise ValueError("secret key's public half does not match its seed")
    return key


def public_key_bytes(key: Ed25519PrivateKey) -> bytes:
    return key.public_key().public_bytes(Encoding.Raw, PublicFormat.Raw)


def public_key_str(key: Ed25519PrivateKey) -> str:
    return "ed25519:" + b58encode(public_key_bytes(key))


def secret_key_str(key: Ed25519PrivateKey) -> str:
    return "ed25519:" + b58encode(key.private_bytes_raw() + public_key_bytes(key))


def parse_public_key(s: str) -> bytes:
    if not s.startswith("ed25519:"):
        raise ValueError("public key must be ed25519:<base58>")
    raw = b58decode(s.removeprefix("ed25519:"))
    if len(raw) != 32:
        raise ValueError("public key must be 32 bytes")
    return raw


# ---------------------------------------------------------------------------------------------
# Actions and transactions (borsh)
# ---------------------------------------------------------------------------------------------


def _u32(v: int) -> bytes:
    return v.to_bytes(4, "little")


def _u64(v: int) -> bytes:
    return v.to_bytes(8, "little")


def _u128(v: int) -> bytes:
    return v.to_bytes(16, "little")


def _str(s: str) -> bytes:
    b = s.encode()
    return _u32(len(b)) + b


def _bytes(b: bytes) -> bytes:
    return _u32(len(b)) + b


@dataclass(frozen=True)
class CreateAccount:
    def borsh(self) -> bytes:
        return bytes([0])


@dataclass(frozen=True)
class DeployContract:
    code: bytes

    def borsh(self) -> bytes:
        return bytes([1]) + _bytes(self.code)


@dataclass(frozen=True)
class FunctionCall:
    method: str
    args: dict[str, Any] = field(default_factory=dict)
    gas: int = 30 * TGAS
    deposit: int = 0  # yoctoNEAR

    def borsh(self) -> bytes:
        body = json.dumps(self.args, separators=(",", ":")).encode()
        return bytes([2]) + _str(self.method) + _bytes(body) + _u64(self.gas) + _u128(self.deposit)


@dataclass(frozen=True)
class Transfer:
    deposit: int  # yoctoNEAR

    def borsh(self) -> bytes:
        return bytes([3]) + _u128(self.deposit)


@dataclass(frozen=True)
class AddFullAccessKey:
    public_key: bytes

    def borsh(self) -> bytes:
        # AddKey { public_key, access_key { nonce: 0, permission: FullAccess (1) } }
        return bytes([5, 0]) + self.public_key + _u64(0) + bytes([1])


Action = CreateAccount | DeployContract | FunctionCall | Transfer | AddFullAccessKey


def encode_transaction(
    signer_id: str,
    public_key: bytes,
    nonce: int,
    receiver_id: str,
    block_hash: bytes,
    actions: list[Action],
) -> bytes:
    if len(public_key) != 32 or len(block_hash) != 32:
        raise ValueError("public key and block hash must be 32 bytes")
    return (
        _str(signer_id)
        + bytes([0])
        + public_key
        + _u64(nonce)
        + _str(receiver_id)
        + block_hash
        + _u32(len(actions))
        + b"".join(a.borsh() for a in actions)
    )


def sign_transaction(key: Ed25519PrivateKey, tx: bytes) -> tuple[bytes, str]:
    """Returns (borsh SignedTransaction, base58 transaction hash)."""
    h = hashlib.sha256(tx).digest()
    return tx + bytes([0]) + key.sign(h), b58encode(h)


# ---------------------------------------------------------------------------------------------
# RPC
# ---------------------------------------------------------------------------------------------


class TxError(RpcError):
    """The transaction was included but an action failed (for example a contract panic)."""


def _call(rpc_url: str, method: str, params: Any, timeout: float) -> Any:
    payload = {"jsonrpc": "2.0", "id": "twooptions-agent", "method": method, "params": params}
    body = post(rpc_url, payload, timeout)
    if "error" in body:
        raise RpcError(f"{method}: {json.dumps(body['error'])[:400]}")
    return body["result"]


def _failure_text(failure: Any) -> str:
    """Pull the contract's panic message out of a nested Failure object."""
    text = json.dumps(failure)
    marker = "Smart contract panicked: "
    i = text.find(marker)
    if i >= 0:
        return text[i + len(marker) :].split('"')[0].rstrip("\\")
    return text[:400]


@dataclass(frozen=True)
class TxResult:
    tx_hash: str
    logs: list[str]
    value: Any  # decoded JSON return value, or None


class Account:
    """One NEAR account and one of its access keys. Not thread-safe: use one per sender thread,
    because access-key nonces must go up one at a time."""

    def __init__(self, rpc_url: str, account_id: str, key: Ed25519PrivateKey, timeout: float = 30):
        self.rpc_url = rpc_url
        self.account_id = account_id
        self.key = key
        self.timeout = timeout
        self._nonce: int | None = None

    @property
    def public_key(self) -> str:
        return public_key_str(self.key)

    def _access_key(self) -> tuple[int, bytes]:
        r = _call(
            self.rpc_url,
            "query",
            {
                "request_type": "view_access_key",
                "finality": "optimistic",
                "account_id": self.account_id,
                "public_key": self.public_key,
            },
            self.timeout,
        )
        if "error" in r:
            raise RpcError(f"access key for {self.account_id}: {r['error']}")
        return int(r["nonce"]), b58decode(r["block_hash"])

    def _submit(self, signed: bytes, tx_hash: str) -> Any:
        """Send and wait until every receipt has executed, so a contract panic comes back here.

        Some providers answer HTTP 408 when that wait outlasts their own limit. The transaction
        is usually already on its way, so ask for its outcome instead of reporting a failure.
        """
        wait = "EXECUTED_OPTIMISTIC"
        try:
            return _call(
                self.rpc_url,
                "send_tx",
                {"signed_tx_base64": base64.b64encode(signed).decode(), "wait_until": wait},
                self.timeout,
            )
        except RpcError as e:
            if "HTTP 408" not in str(e):
                raise
        last: Exception | None = None
        for _ in range(6):
            time.sleep(1.0)
            try:
                return _call(
                    self.rpc_url,
                    "tx",
                    {"tx_hash": tx_hash, "sender_account_id": self.account_id, "wait_until": wait},
                    self.timeout,
                )
            except RpcError as e:  # not known yet, or still waiting
                last = e
        raise RpcError(f"{tx_hash}: no outcome after a timeout ({last})")

    def send(self, receiver_id: str, actions: list[Action]) -> TxResult:
        chain_nonce, block_hash = self._access_key()
        nonce = max(chain_nonce, self._nonce or 0) + 1
        tx = encode_transaction(
            self.account_id, public_key_bytes(self.key), nonce, receiver_id, block_hash, actions
        )
        signed, tx_hash = sign_transaction(self.key, tx)
        try:
            r = self._submit(signed, tx_hash)
        except Exception:
            self._nonce = None  # unknown whether it landed; re-read the nonce next time
            raise
        self._nonce = nonce
        logs = [
            line
            for o in r.get("receipts_outcome", [])
            for line in o.get("outcome", {}).get("logs", [])
        ]
        failures = [r.get("status", {})] + [
            o.get("outcome", {}).get("status", {}) for o in r.get("receipts_outcome", [])
        ]
        for st in failures:
            if isinstance(st, dict) and "Failure" in st:
                raise TxError(f"{tx_hash}: {_failure_text(st['Failure'])}")
        value = None
        raw = r.get("status", {}).get("SuccessValue")
        if raw:
            try:
                value = json.loads(base64.b64decode(raw))
            except ValueError:
                value = None
        return TxResult(tx_hash, logs, value)

    def call(
        self,
        receiver_id: str,
        method: str,
        args: dict[str, Any] | None = None,
        gas: int = 30 * TGAS,
        deposit: int = 0,
    ) -> TxResult:
        return self.send(receiver_id, [FunctionCall(method, args or {}, gas, deposit)])
