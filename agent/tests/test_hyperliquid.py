def test_signatures_recover_to_the_signer_and_a_changed_digest_does_not() -> None:
    rng = random.Random(5)
    for _ in range(8):
        digest = rng.randbytes(32)
        r, s, v = SIGNER.sign_digest(digest)
        assert s <= hl._N // 2 and v in (27, 28)
        assert hl.recover(digest, r, s, v - 27) == SIGNER.public
        assert hl.recover(digest, r, s, 28 - v) != SIGNER.public  # the other candidate key
        tampered = bytes([digest[0] ^ 1]) + digest[1:]
        assert hl.recover(tampered, r, s, v - 27) != SIGNER.public


