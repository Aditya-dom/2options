META = {
    "universe": [
        {"szDecimals": 2, "name": "SOL", "maxLeverage": 10},
        {"szDecimals": 5, "name": "BTC", "maxLeverage": 40},
        {"szDecimals": 4, "name": "ETH", "maxLeverage": 25},
    ]
}
STATE = {
    "assetPositions": [
        {
            "type": "oneWay",
            "position": {
                "coin": "ETH",
                "szi": "-0.25",
                "entryPx": "1990.5",
                "unrealizedPnl": "1.05",
                "positionValue": "496.5",
            },
        },
        {"type": "oneWay", "position": {"coin": "BTC", "szi": "0.0", "entryPx": None}},
    ],
    "marginSummary": {"accountValue": "1451.041001", "totalMarginUsed": "19.86"},
    "withdrawable": "1431.18",
    "time": 1794519063150,
}


class FakeHttp:
    def __init__(self) -> None:
        self.calls: list[tuple[str, dict[str, Any]]] = []
        self.mode = "default"
        self.exchange: Any = {
            "status": "ok",
            "response": {
                "type": "order",
                "data": {
                    "statuses": [{"filled": {"totalSz": "0.5", "avgPx": "1988.9", "oid": 77}}]
                },
            },
        }

    def __call__(self, path: str, body: dict[str, Any]) -> Any:
        self.calls.append((path, body))
        if path == "/exchange":
            return self.exchange
        if body["type"] == "userAbstraction":
            return self.mode
        if body["type"] == "spotClearinghouseState":
            return {"balances": [{"coin": "USDC", "total": "999.0", "hold": "19.5"}, {"coin": "HYPE", "total": "3.0", "hold": "0.0"}]}  # fmt: skip
        return {"meta": META, "allMids": {"ETH": "1986.3", "BTC": "73317.5"}}.get(
            body["type"], STATE
        )


def test_reads_parse_into_decimals_and_drop_empty_positions() -> None:
    http = FakeHttp()
    venue = hl.Hyperliquid(SIGNER, "testnet", http=http)
    assert venue.account == V["address"]
    assert venue.assets()["ETH"] == hl.Asset("ETH", 2, 4)
    venue.assets()
    assert [b["type"] for _, b in http.calls] == ["meta"]  # cached
    assert venue.mids()["ETH"] == Decimal("1986.3")
    st = venue.state()
    assert st.account_value == Decimal("1451.041001") and st.withdrawable == Decimal("1431.18")
    assert st.positions == {
        "ETH": hl.Position("ETH", Decimal("-0.25"), Decimal("1990.5"), Decimal("1.05"))
    }
    assert ("/info", {"type": "clearinghouseState", "user": V["address"]}) in http.calls
    assert not any(b["type"] == "spotClearinghouseState" for _, b in http.calls)


def test_a_unified_account_counts_the_spot_usdc_that_backs_its_perps() -> None:
    """Seen live on testnet: 999 USDC in the spot balance, a perp balance of zero, and orders
    that fill. Reading only the perp balance reported an empty account. With a position open,
    its margin shows up both as the perp balance and as `hold` on the spot side."""
    http = FakeHttp()
    http.mode = "unifiedAccount"
    venue = hl.Hyperliquid(SIGNER, "testnet", http=http)
    st = venue.state()
    assert st.account_value == Decimal("1451.041001") + Decimal("979.5")  # 999.0 less 19.5 held
    assert st.withdrawable == Decimal("1431.18") + Decimal("979.5")
    assert st.positions["ETH"].size == Decimal("-0.25")
    venue.state()
    assert [b["type"] for _, b in http.calls].count("userAbstraction") == 1  # the mode is cached


def test_an_api_wallet_reads_the_master_accounts_positions() -> None:
    http = FakeHttp()
    master = "0x" + "AB" * 20
    venue = hl.Hyperliquid(SIGNER, "testnet", account=master, http=http)
    venue.state()
    assert {b["user"] for _, b in http.calls if "user" in b} == {master.lower()}
    with pytest.raises(ValueError):
        hl.Hyperliquid(SIGNER, "testnet", account="0x1234", http=http)
    with pytest.raises(ValueError):
        hl.Hyperliquid(SIGNER, "devnet", http=http)


def test_an_order_is_signed_for_its_network_and_carries_its_expiry() -> None:
    http = FakeHttp()
    venue = hl.Hyperliquid(SIGNER, "testnet", http=http)
    res = venue.ioc("ETH", True, Decimal("0.5"), Decimal("2006.2"), False, 1_794_519_071_150)
    assert res == hl.OrderResult("filled", Decimal("0.5"), Decimal("1988.9"), 77)
    path, body = http.calls[-1]
    assert path == "/exchange" and body["vaultAddress"] is None
    assert body["expiresAfter"] == 1_794_519_071_150
    assert body["action"] == {
        "type": "order",
        "orders": [
            {"a": 2, "b": True, "p": "2006.2", "s": "0.5", "r": False, "t": {"limit": {"tif": "Ioc"}}}
        ],
        "grouping": "na",
    }  # fmt: skip
    # The signature is over exactly what was sent, for testnet, and recovers to the signer.
    digest = hl.agent_digest(
        hl.action_hash(body["action"], None, body["nonce"], body["expiresAfter"]), False
    )
    sig = body["signature"]
    assert hl.recover(digest, int(sig["r"], 16), int(sig["s"], 16), sig["v"] - 27) == SIGNER.public
    mainnet = hl.agent_digest(
        hl.action_hash(body["action"], None, body["nonce"], body["expiresAfter"]), True
    )
    assert hl.recover(mainnet, int(sig["r"], 16), int(sig["s"], 16), sig["v"] - 27) != SIGNER.public


def test_nonces_never_repeat() -> None:
    http = FakeHttp()
    venue = hl.Hyperliquid(SIGNER, "testnet", http=http)
    nonces = []
    for _ in range(5):
        venue.ioc("ETH", False, Decimal("0.01"), Decimal("1900"), True, 2_000_000_000_000)
        nonces.append(http.calls[-1][1]["nonce"])
    assert nonces == sorted(set(nonces))


