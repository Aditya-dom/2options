"""Parity with the official Hyperliquid SDK, from tests/fixtures/hyperliquid_vectors.json
(generated by scripts/hl_vectors.py), plus the vectors in the SDK's own test suite."""

import hashlib
import json
import random
from decimal import Decimal
from pathlib import Path
from typing import Any

import pytest

from twooptions_agent import hyperliquid as hl
from twooptions_agent.keccak import keccak256, sponge256

V = json.loads((Path(__file__).parent / "fixtures" / "hyperliquid_vectors.json").read_text())
SIGNER = hl.Signer(V["key"])


def test_keccak_matches_the_reference_and_the_sponge_matches_hashlib() -> None:
    for c in V["keccak"]:
        assert keccak256(bytes.fromhex(c["in"])).hex() == c["out"]
    assert keccak256(b"").hex() == (
        "c5d2460186f7233c927e7db2dcc703c0e500b653ca82273b7bfad8045d85a470"
    )
    # Same permutation as SHA3-256, different padding byte: hashlib checks the hard part.
    rng = random.Random(3)
    for n in [*range(0, 140), 271, 272, 273, 1_000]:
        m = rng.randbytes(n)
        assert sponge256(m, 0x06) == hashlib.sha3_256(m).digest()
        assert keccak256(m) != hashlib.sha3_256(m).digest()


def test_msgpack_matches_the_reference_encoder() -> None:
    for c in V["msgpack"]:
        assert hl.msgpack(c["obj"]).hex() == c["hex"], c["obj"]
    # Longer than the fixture carries: str32 and array32 headers.
    assert hl.msgpack("q" * 70_000)[:5] == b"\xdb" + (70_000).to_bytes(4, "big")
    assert hl.msgpack([0] * 70_000)[:5] == b"\xdd" + (70_000).to_bytes(4, "big")


@pytest.mark.parametrize("bad", [1.5, b"bytes", {1: "int key"}, 2**64, -(2**63) - 1])
def test_msgpack_refuses_what_it_does_not_encode(bad: Any) -> None:
    with pytest.raises((TypeError, ValueError)):
        hl.msgpack(bad)


def test_address_is_derived_as_ethereum_does() -> None:
    assert SIGNER.address == V["address"]


def test_action_hash_digest_and_signature_match_the_sdk() -> None:
    assert len(V["l1"]) == 48
    for c in V["l1"]:
        h = hl.action_hash(c["action"], c["vault"], c["nonce"], c["expires_after"])
        assert h.hex() == c["connection_id"]
        digest = hl.agent_digest(h, c["is_mainnet"])
        assert digest.hex() == c["digest"]
        sig = hl.sign_l1_action(
            SIGNER, c["action"], c["vault"], c["nonce"], c["expires_after"], c["is_mainnet"]
        )
        assert sig == c["signature"]


