def test_wire_numbers_match_the_sdk() -> None:
    for c in V["wire"]:
        assert hl.to_wire(Decimal(c["value"])) == c["wire"]
    assert hl.to_wire(Decimal("-0.0")) == "0"
    with pytest.raises(ValueError):
        hl.to_wire(Decimal("0.123456789"))


def test_price_rounding_is_valid_and_within_a_tick_of_the_sdk() -> None:
    """The venue's rule is 5 significant figures and `6 - sz_decimals` decimals. The SDK rounds
    through binary floats, so on an exact decimal tie it can differ from this by one tick."""
    assert len(V["prices"]) > 150
    exact = 0
    for c in V["prices"]:
        got = hl.round_price(Decimal(c["px"]), c["sz_decimals"])
        tick = Decimal(1).scaleb(-(hl.MAX_PRICE_DECIMALS - c["sz_decimals"]))
        assert got > 0 and got % tick == 0, c
        assert len(got.normalize().as_tuple().digits) <= hl.PRICE_SIG_FIGS, c
        assert abs(got - Decimal(c["wire"])) <= tick, c
        exact += hl.to_wire(got) == c["wire"]
    assert exact >= len(V["prices"]) - 3
    with pytest.raises(ValueError):
        hl.round_price(Decimal("0.0000001"), 4)
    with pytest.raises(ValueError):
        hl.round_price(Decimal("-1"), 4)


def test_sizes_round_down_to_the_lot() -> None:
    assert hl.floor_size(Decimal("0.49999"), 4) == Decimal("0.4999")
    assert hl.floor_size(Decimal("12.99"), 1) == Decimal("12.9")
    assert hl.floor_size(Decimal("0.00009"), 4) == 0


